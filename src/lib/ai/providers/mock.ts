import type { AIProvider } from "@/lib/ai/providers/types";
import {
  reviewAnalysisSchema,
  type ReviewAnalysis,
  type ReviewAnalysisInput,
} from "@/lib/ai/schemas/review-analysis";
import {
  isTestimonialCandidate,
  ratingToSentiment,
  shouldEscalate,
} from "@/lib/reviews/rules";

/**
 * Deterministic mock provider. Requires no API key and produces realistic,
 * policy-compliant output so the whole product works end-to-end out of the box.
 */
export class MockAIProvider implements AIProvider {
  readonly name = "mock";
  readonly model = "mock-deterministic-v1";

  async analyzeReview(input: ReviewAnalysisInput): Promise<ReviewAnalysis> {
    const rating = input.rating;
    const sentiment = inferSentiment(input.review_text, rating);
    const severity = inferSeverity(sentiment, rating);
    const escalate = shouldEscalate(rating, { severity, should_escalate: false });
    const apology = sentiment === "negative";
    const testimonial = isTestimonialCandidate(rating, { sentiment });

    const reply = buildReply(input, sentiment);
    const social = testimonial ? buildSocialPost(input) : "";

    const analysis: ReviewAnalysis = {
      sentiment,
      severity,
      should_escalate: escalate,
      suggested_reply: reply,
      reply_tone: input.brand_tone,
      key_points: extractKeyPoints(input.review_text),
      apology_needed: apology,
      avoid_phrases: [
        "admitting legal fault",
        "sharing private customer details",
        "offering incentives to change the review",
      ],
      testimonial_candidate: testimonial,
      social_post_draft: social,
      confidence: rating === null ? 0.55 : 0.82,
    };

    // Validate our own output so the mock can never drift from the contract.
    return reviewAnalysisSchema.parse(analysis);
  }

  async summarize(prompt: string): Promise<string> {
    // Echo a structured, deterministic summary based on the supplied metrics.
    return [
      "Weekly reputation summary (generated by mock AI):",
      "",
      prompt.trim(),
      "",
      "Recommended next actions:",
      "- Reply to any reviews still awaiting approval.",
      "- Send review requests to recently served happy customers.",
      "- Turn your best 5-star reviews into testimonials and social posts.",
    ].join("\n");
  }
}

function inferSentiment(
  text: string,
  rating: number | null,
): "positive" | "neutral" | "negative" {
  if (rating !== null) return ratingToSentiment(rating);
  const t = text.toLowerCase();
  const negative = ["terrible", "awful", "rude", "late", "broken", "refund", "worst", "never again", "disappointed"];
  const positive = ["great", "excellent", "amazing", "professional", "friendly", "recommend", "fantastic", "perfect", "love"];
  const negHit = negative.some((w) => t.includes(w));
  const posHit = positive.some((w) => t.includes(w));
  if (negHit && !posHit) return "negative";
  if (posHit && !negHit) return "positive";
  return "neutral";
}

function inferSeverity(
  sentiment: "positive" | "neutral" | "negative",
  rating: number | null,
): "low" | "medium" | "high" {
  if (sentiment === "negative") return rating !== null && rating <= 1 ? "high" : "medium";
  return "low";
}

function buildReply(
  input: ReviewAnalysisInput,
  sentiment: "positive" | "neutral" | "negative",
): string {
  const name = input.reviewer_name?.trim() || "there";
  const biz = input.business_name;
  if (sentiment === "negative") {
    return (
      `Hi ${name}, thank you for taking the time to share this feedback, and I'm sorry your ` +
      `experience with ${biz} fell short. I'd genuinely like to understand what happened and ` +
      `make it right. Please reach out to us directly so we can resolve this for you.`
    );
  }
  if (sentiment === "neutral") {
    return (
      `Hi ${name}, thanks for the honest feedback about ${biz}. We're always working to improve, ` +
      `and I'd love to hear how we could have made your experience a 5-star one. Feel free to ` +
      `reach out to us anytime.`
    );
  }
  return (
    `Hi ${name}, thank you so much for the kind words! The whole ${biz} team really appreciates ` +
    `it, and we're glad we could help. We look forward to working with you again.`
  );
}

function buildSocialPost(input: ReviewAnalysisInput): string {
  const name = input.reviewer_name?.trim() || "A happy customer";
  return (
    `⭐⭐⭐⭐⭐ Another happy customer!\n\n` +
    `"${truncate(input.review_text, 180)}"\n— ${name}\n\n` +
    `Thank you for trusting ${input.business_name}. ` +
    `Ready to experience it yourself? Get in touch today.`
  );
}

function extractKeyPoints(text: string): string[] {
  return text
    .split(/[.!?\n]+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 12)
    .slice(0, 3);
}

function truncate(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max - 1).trimEnd()}…`;
}
